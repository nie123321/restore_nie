import argparse
import json
import math
import os
from pathlib import Path
import random
import time
import uuid

import numpy as np
import torch
from torch.utils.data import DataLoader

from dataset import PairedImages, StepBatches
from losses import gt_mean_fft_l1, VGGPerceptualMSE
from metrics import psnr, ssim
from models import EnhancementNet
from models.checkpoint import MODEL_VARIANT, validate_model_config
from runtime_utils import (RunLock, atomic_json, configure_fp32, output_entries,
                           source_manifest, snapshot_source, split_manifest_info)

TRAINING_PROTOCOL = 'v3-mswf-ab-20261019-vgg0005'
CONFIG_KEYS = {'steps', 'batch_size', 'crop_size', 'seed', 'workers', 'lr', 'min_lr',
               'lr_schedule', 'cosine_steps', 'weight_decay', 'grad_clip', 'geometric_augs',
               'saturation_probability', 'saturation_range', 'gt_mean_sigma', 'fft_weight',
               'eval_every', 'save_every', 'eval_split', 'eval_domain', 'data_root',
               'amp', 'loss_mode', 'training_protocol', 'vgg_weight', 'vgg_weights_file'}


def learning_rate(config, step):
    progress = min(1.0, (step - 1) / max(1, config['cosine_steps'] - 1))
    return config['min_lr'] + .5 * (config['lr'] - config['min_lr']) * (1 + math.cos(math.pi * progress))


def rng_state():
    name, keys, position, has_gauss, cached = np.random.get_state()
    return {'python': random.getstate(), 'torch': torch.get_rng_state(),
            'cuda': torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
            'numpy': {'algorithm': name, 'keys': keys.tolist(), 'position': int(position),
                      'has_gauss': int(has_gauss), 'cached_gaussian': float(cached)}}


def restore_rng(state):
    random.setstate(state['python'])
    value = state['numpy']
    np.random.set_state((value['algorithm'], np.asarray(value['keys'], dtype=np.uint32),
                         value['position'], value['has_gauss'], value['cached_gaussian']))
    torch.set_rng_state(state['torch'])
    if state['cuda'] is not None and torch.cuda.is_available():
        torch.cuda.set_rng_state_all(state['cuda'])


def save_checkpoint(state, path, replace=False):
    if path.exists() and not replace:
        raise FileExistsError(f'Checkpoint already exists: {path}')
    temporary = path.with_name(f'.s.{uuid.uuid4().hex[:12]}.tmp')
    try:
        with temporary.open('wb') as stream:
            torch.save(state, stream)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


@torch.no_grad()
def evaluate(model, loader, device, split, domain):
    model.eval()
    psnr_sum, ssim_sum = 0.0, 0.0
    for low, target in loader:
        target = target.to(device)
        output = model(low.to(device))
        if not torch.isfinite(output).all():
            raise RuntimeError('Nonfinite evaluation output')
        output = output.clamp(0, 1)
        if domain == 'rgb_uint8':
            reference = np.rint(target[0].permute(1, 2, 0).cpu().numpy() * 255).astype(np.uint8)
            prediction = np.rint(output[0].permute(1, 2, 0).cpu().numpy() * 255).astype(np.uint8)
            psnr_sum += psnr(reference, prediction)
        else:
            mse = float((output - target).square().mean())
            psnr_sum += -10 * math.log10(max(mse, 1e-12))
            reference = target[0].permute(1, 2, 0).cpu().numpy().astype(np.float64) * 255
            prediction = output[0].permute(1, 2, 0).cpu().numpy().astype(np.float64) * 255
        ssim_sum += ssim(reference, prediction)
    model.train()
    return {f'{split}_psnr': psnr_sum / len(loader), f'{split}_ssim': ssim_sum / len(loader)}


def check_resume(checkpoint, config):
    if checkpoint['training_protocol'] != TRAINING_PROTOCOL:
        raise ValueError('Resume requires a checkpoint generated by this training release')
    previous = checkpoint['config']
    validate_model_config(previous['model'])
    for key in (CONFIG_KEYS - {'workers'}) | {'model', 'split_manifest'}:
        if previous[key] != config[key]:
            raise ValueError(f'Resume configuration differs: {key}')


def trim_log_for_resume(path, step):
    if not path.exists():
        return
    retained = []
    for line in path.read_text(encoding='utf-8').splitlines():
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            break
        if row['step'] <= step:
            retained.append(line)
    temporary = path.with_name(f'.l.{uuid.uuid4().hex[:12]}.tmp')
    try:
        temporary.write_text(''.join(line + '\n' for line in retained), encoding='utf-8')
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def run(args, config, device):
    output = args.output
    with RunLock(output):
        if output_entries(output) and args.resume is None:
            raise ValueError('Use an empty output directory or --resume')
        random.seed(config['seed'])
        np.random.seed(config['seed'])
        torch.manual_seed(config['seed'])
        model = EnhancementNet().to(device=device, dtype=torch.float32)
        config['model'] = model.config
        config['split_manifest'] = split_manifest_info(args.data_root)
        if config['split_manifest'] is None:
            raise FileNotFoundError(f'Dataset split_manifest.csv is missing: {args.data_root}')
        manifest = source_manifest(Path(__file__).resolve().parent)
        config['source_sha256'] = manifest['sha256']
        optimizer = torch.optim.AdamW(model.parameters(), lr=config['lr'], weight_decay=config['weight_decay'])
        start, checkpoint = 0, None
        selection = {'eval_split': config['eval_split'], 'eval_domain': config['eval_domain'],
                     'best_psnr': None, 'best_ssim': None}
        if args.resume is not None:
            checkpoint = torch.load(args.resume, map_location='cpu', weights_only=False)
            check_resume(checkpoint, config)
            if checkpoint['source_sha256'] != manifest['sha256']:
                raise ValueError('Resume source/config fingerprint differs from the checkpoint')
            model.load_state_dict(checkpoint['model'], strict=True)
            optimizer.load_state_dict(checkpoint['optimizer'])
            start = int(checkpoint['step'])
            if checkpoint['sampling_step'] != start:
                raise ValueError('Checkpoint sampling step is inconsistent')
            if any(int(path.stem.split('_')[-1]) > start for path in output.glob('step_*.pt')):
                raise ValueError('A newer checkpoint exists here; resume the latest checkpoint')
            selection = checkpoint['selection']
        if start >= config['steps']:
            raise ValueError('Training already reached the configured number of steps')
        train_set = PairedImages(args.data_root, 'train', crop_size=config['crop_size'], seed=config['seed'],
                                 geometric_augs=config['geometric_augs'],
                                 saturation_probability=config['saturation_probability'],
                                 saturation_range=config['saturation_range'])
        names = [path.name for path in train_set.low]
        if checkpoint is not None and checkpoint['train_filenames'] != names:
            raise ValueError('Training image list changed since the checkpoint')
        stop = min(config['steps'], start + args.stop_after) if args.stop_after else config['steps']
        sampler = StepBatches(len(train_set), config['batch_size'], config['seed'], start, stop,
                              geometric_augs=config['geometric_augs'])
        loader = DataLoader(train_set, batch_sampler=sampler, num_workers=config['workers'],
                            generator=torch.Generator().manual_seed(config['seed'] + 100000),
                            pin_memory=device.type == 'cuda')
        eval_set = PairedImages(args.data_root, config['eval_split']) if config['eval_every'] else None
        eval_loader = DataLoader(eval_set, batch_size=1, num_workers=config['workers'],
                                 generator=torch.Generator().manual_seed(config['seed'] + 200000)) if eval_set is not None else None
        if checkpoint is not None:
            restore_rng(checkpoint['rng'])
        snapshot_source(Path(__file__).resolve().parent, output, manifest)
        atomic_json(output / 'config.json', config)
        if checkpoint is not None:
            trim_log_for_resume(output / 'train.jsonl', start)
        status = {'state': 'running', 'pid': os.getpid(), 'variant': MODEL_VARIANT, 'device': str(device),
                  'start_step': start, 'step': start, 'requested_stop': stop,
                  'train_images': len(train_set), 'eval_images': len(eval_set) if eval_set is not None else 0,
                  'eval_split': config['eval_split'], 'eval_domain': config['eval_domain'],
                  'latest_checkpoint': str(args.resume) if args.resume else None}
        atomic_json(output / 'status.json', status)
        print(f"variant={MODEL_VARIANT}, train={len(train_set)}, {config['eval_split']}={status['eval_images']}, "
              f"start={start}, stop={stop}, cosine horizon={config['cosine_steps']}", flush=True)
        vgg = VGGPerceptualMSE(Path(__file__).resolve().parent / config['vgg_weights_file']).to(device) if config['vgg_weight'] > 0 else None
        print(f"vgg_weight={config['vgg_weight']}", flush=True)
        model.train()
        try:
            with (output / 'train.jsonl').open('a', encoding='utf-8') as log:
                for step, (low, target) in enumerate(loader, start=start + 1):
                    began = time.perf_counter()
                    lr = learning_rate(config, step)
                    for group in optimizer.param_groups:
                        group['lr'] = lr
                    optimizer.zero_grad(set_to_none=True)
                    target_device = target.to(device)
                    prediction = model(low.to(device))
                    loss, _ = gt_mean_fft_l1(prediction, target_device,
                                             sigma=config['gt_mean_sigma'], fft_weight=config['fft_weight'])
                    perceptual = None
                    if vgg is not None:
                        perceptual = vgg(prediction, target_device)
                        loss = loss + config['vgg_weight'] * perceptual
                    if not torch.isfinite(loss):
                        raise RuntimeError(f'Nonfinite loss at step {step}')
                    loss.backward()
                    torch.nn.utils.clip_grad_norm_(model.parameters(), config['grad_clip'], error_if_nonfinite=True)
                    optimizer.step()
                    status['step'] = step
                    row = {'step': step, 'loss': float(loss.detach()), 'lr': lr,
                           'loss_vgg': float(perceptual.detach()) if perceptual is not None else 0.0,
                           'seconds': time.perf_counter() - began}
                    improved = []
                    if eval_loader is not None and step % config['eval_every'] == 0:
                        row.update(evaluate(model, eval_loader, device, config['eval_split'], config['eval_domain']))
                        point = {'step': step, 'psnr': row[f"{config['eval_split']}_psnr"],
                                 'ssim': row[f"{config['eval_split']}_ssim"]}
                        for key, metric in (('best_psnr', 'psnr'), ('best_ssim', 'ssim')):
                            previous = selection[key]
                            if previous is None or point[metric] > previous[metric]:
                                selection[key] = dict(point)
                                improved.append(key)
                    log.write(json.dumps(row, allow_nan=False) + '\n')
                    log.flush()
                    if step == start + 1 or step % 50 == 0 or step == stop:
                        print(json.dumps(row), flush=True)
                    if step % config['save_every'] == 0 or step == stop or improved:
                        state = {'model': model.state_dict(), 'optimizer': optimizer.state_dict(),
                                 'step': step, 'sampling_step': step, 'config': config, 'rng': rng_state(),
                                 'source_sha256': manifest['sha256'], 'train_filenames': names,
                                 'training_protocol': TRAINING_PROTOCOL, 'selection': selection,
                                 'eval_metrics': {k: v for k, v in row.items() if k.startswith(config['eval_split'] + '_')}}
                        path = output / f'step_{step:06d}.pt'
                        save_checkpoint(state, path)
                        save_checkpoint(state, output / 'last.pt', replace=True)
                        for key in improved:
                            save_checkpoint(state, output / f'{key}.pt', replace=True)
                        atomic_json(output / 'selection.json', selection)
                        status['latest_checkpoint'] = str(path)
                    if step % 50 == 0 or step == start + 1 or step == stop:
                        atomic_json(output / 'status.json', status)
            status['state'] = 'complete' if stop == config['steps'] else 'paused_by_stop_after'
            atomic_json(output / 'status.json', status)
        except BaseException as error:
            status.update(state='interrupted' if isinstance(error, KeyboardInterrupt) else 'failed',
                          error_type=type(error).__name__, error=str(error))
            atomic_json(output / 'status.json', status)
            raise


def main():
    parser = argparse.ArgumentParser(description='Standalone V3 MSWF variant: FP32 train, evaluate and resume')
    parser.add_argument('--data-root', type=Path, help='Defaults to the selected config')
    parser.add_argument('--output', '--run-dir', dest='output', type=Path)
    parser.add_argument('--config', type=Path, default=Path(__file__).with_name('config.json'))
    parser.add_argument('--resume', type=Path)
    parser.add_argument('--device', default='cuda' if torch.cuda.is_available() else 'cpu')
    parser.add_argument('--batch-size', type=int)
    parser.add_argument('--workers', type=int)
    parser.add_argument('--seed', type=int)
    parser.add_argument('--stop-after', type=int, default=0, help='Additional steps; cosine horizon unchanged')
    parser.add_argument('--amp', action='store_true', help='Unsupported; this release uses FP32')
    args = parser.parse_args()
    config = json.loads(args.config.read_text(encoding='utf-8-sig'))
    if set(config) != CONFIG_KEYS:
        parser.error(f'Config fields differ: missing={sorted(CONFIG_KEYS-set(config))}, extra={sorted(set(config)-CONFIG_KEYS)}')
    for key in ('batch_size', 'workers', 'seed'):
        if getattr(args, key) is not None:
            config[key] = getattr(args, key)
    args.data_root = (args.data_root or Path(config['data_root'])).resolve()
    args.output = (args.output or Path(__file__).resolve().parent / 'outputs' / f"seed{config['seed']}").resolve()
    config['data_root'] = str(args.data_root)
    if args.amp or config['amp'] or config['loss_mode'] != 'gt-mean-fft':
        parser.error('This release uses FP32 and GT-Mean + FFT loss')
    if config['training_protocol'] != TRAINING_PROTOCOL or config['lr_schedule'] != 'cosine':
        parser.error('Unsupported training protocol or schedule')
    if config['eval_split'] not in ('val', 'test') or config['eval_domain'] not in ('rgb_uint8', 'rgb_float'):
        parser.error('Unsupported evaluation split/domain')
    if (config['batch_size'] < 1 or config['workers'] < 0 or config['steps'] < 1 or args.stop_after < 0
            or config['save_every'] < 1 or config['eval_every'] < 0
            or not 1 <= config['cosine_steps'] <= config['steps']):
        parser.error('Invalid batch size, workers, steps or periods')
    if len(config['crop_size']) != 2 or min(config['crop_size']) < 1:
        parser.error('crop_size must contain two positive dimensions')
    configure_fp32()
    device = torch.device(args.device)
    if device.type == 'cuda' and not torch.cuda.is_available():
        parser.error('CUDA is unavailable; use --device cpu for CPU checks')
    run(args, config, device)


if __name__ == '__main__':
    main()
